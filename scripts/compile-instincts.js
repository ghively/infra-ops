#!/usr/bin/env node
/**
 * Instinct recall compiler — closes the learning loop (decision
 * 2026-07-17-close-the-learning-loop.md).
 *
 * The observe → promote → ledger pipeline WRITES instincts but nothing READ them back,
 * so promoted instincts changed no behavior. This compiler is the recall side: it reads
 * every ACTIVE instinct for a zone and emits a path-scoped rule fragment under
 * `rules/instincts/<zone>/<id>.md`. The harness already injects `rules/**` deterministically
 * whenever a matching file is in context, so compiled instincts now reach agent context
 * on the exact rail the accepted decision chose (rules-rail, not a bespoke loader).
 *
 * Reads both formats:
 *   - seed files:      knowledge/instincts/<zone>/*.yaml with a top-level `instincts:` array
 *   - promoted singles: knowledge/instincts/<zone>/<id>.yml (single instinct object)
 * Skips the `.versions/` snapshot subdir and any instinct whose status is not active.
 *
 * Usage:
 *   node scripts/compile-instincts.js [--zone corporate|hsa]   # default: corporate
 */

'use strict';

const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');

const REPO_ROOT = path.resolve(__dirname, '..');
const INSTINCTS_ROOT = path.join(REPO_ROOT, 'knowledge', 'instincts');
const RULES_ROOT = path.join(REPO_ROOT, 'rules', 'instincts');

// Default path scope by category when an instinct has no explicit `applies_to`.
const CATEGORY_PATHS = {
  ansible: ['**/*.yml', '**/*.yaml'],
  'gitlab-ci': ['**/.gitlab-ci.yml', '**/*.gitlab-ci.yml', '.gitlab-ci/**'],
  secrets: ['**/*'],
  pci: ['**/*'],
  'supply-chain': ['**/*'],
};

function zoneDir(zone) {
  const z = String(zone || 'corporate').toLowerCase();
  if (z === 'hsa' || z === 'in-zone') return 'hsa';
  return 'corporate';
}

function pathScope(instinct) {
  if (Array.isArray(instinct.applies_to) && instinct.applies_to.length) return instinct.applies_to;
  if (instinct.category && CATEGORY_PATHS[instinct.category]) return CATEGORY_PATHS[instinct.category];
  return ['**/*.yml', '**/*.yaml'];
}

function isActive(instinct) {
  // Seeds may omit status; treat missing as active. Explicit non-active is excluded.
  return !instinct.status || String(instinct.status).toLowerCase() === 'active';
}

// Collect active instincts for a zone from both file formats.
function collectInstincts(zone) {
  const dir = path.join(INSTINCTS_ROOT, zoneDir(zone));
  if (!fs.existsSync(dir)) return [];
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) continue; // skip .versions/ snapshots
    if (!/\.(ya?ml)$/.test(entry.name)) continue;
    let parsed;
    try {
      parsed = yaml.load(fs.readFileSync(path.join(dir, entry.name), 'utf8'));
    } catch {
      continue; // a malformed ledger file is skipped, not fatal
    }
    if (parsed && Array.isArray(parsed.instincts)) {
      for (const it of parsed.instincts) if (it && it.id && isActive(it)) out.push(it);
    } else if (parsed && parsed.id && isActive(parsed)) {
      out.push(parsed);
    }
  }
  return out;
}

function toRuleFragment(instinct) {
  const scope = pathScope(instinct);
  const front = `---\npaths:\n${scope.map((p) => `  - "${p}"`).join('\n')}\n---\n`;
  const conf = instinct.confidence != null ? ` (confidence ${instinct.confidence})` : '';
  const body = String(instinct.content || '').trim();
  const cite = instinct.citation ? `\n\nSource: ${instinct.citation}` : '';
  return `${front}\n<!-- GENERATED by scripts/compile-instincts.js — do not edit by hand. -->\n` +
    `# Learned instinct: ${instinct.id}${conf}\n\n${body}${cite}\n`;
}

/**
 * Compile a zone's active instincts into rules/instincts/<zone>/*.md.
 * Removes stale generated fragments whose instinct is no longer active.
 * @returns {{zone:string, written:number, removed:number}}
 */
function compileZone(zone) {
  const z = zoneDir(zone);
  const outDir = path.join(RULES_ROOT, z);
  fs.mkdirSync(outDir, { recursive: true });

  const instincts = collectInstincts(z);
  const wanted = new Set(instincts.map((i) => `${i.id}.md`));

  // Remove stale generated fragments.
  let removed = 0;
  for (const f of fs.existsSync(outDir) ? fs.readdirSync(outDir) : []) {
    if (f.endsWith('.md') && !wanted.has(f)) {
      const p = path.join(outDir, f);
      if (fs.readFileSync(p, 'utf8').includes('GENERATED by scripts/compile-instincts.js')) {
        fs.unlinkSync(p);
        removed += 1;
      }
    }
  }

  for (const it of instincts) {
    fs.writeFileSync(path.join(outDir, `${it.id}.md`), toRuleFragment(it));
  }
  return { zone: z, written: instincts.length, removed };
}

if (require.main === module) {
  const argv = process.argv.slice(2);
  const zi = argv.indexOf('--zone');
  const zone = zi >= 0 ? argv[zi + 1] : 'corporate';
  const r = compileZone(zone);
  process.stdout.write(`✅ compiled ${r.written} active instinct(s) → rules/instincts/${r.zone}/ (removed ${r.removed} stale)\n`);
}

module.exports = { compileZone, collectInstincts, pathScope, zoneDir };
